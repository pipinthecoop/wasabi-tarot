def recipe(cid):
    seed = int(hashlib.sha256(cid.encode()).hexdigest()[:8], 16)
    if cid.startswith("major-"):
        effects = MAJOR_MOTION[int(cid.split("-")[1])]
    else:
        suit, rank = cid.split("-")
        effects = COURT_MOTION[suit][rank] if rank in COURT_MOTION[suit] else MINOR_MOTION[suit][RANKS.index(rank)]
    return {"effects": effects, "phase": (seed % 997) / 997, "duration_ms": 140 + (seed % 7) * 10, "seed": seed, "frames": FRAMES, "size": list(SIZE)}
